function makeSchema(wordCount: number) {
  return {
    type: "object",
    additionalProperties: false,
    properties: {
      title: { type: "string" },
      body: { type: "string" },
      points: {
        type: "array",
        minItems: 3,
        maxItems: 3,
        items: { type: "string" },
      },
      words: {
        type: "array",
        minItems: wordCount,
        maxItems: wordCount,
        items: {
          type: "object",
          additionalProperties: false,
          properties: {
            term: { type: "string" },
            meaning: { type: "string" },
          },
          required: ["term", "meaning"],
        },
      },
      why: { type: "string" },
      relation: { type: "string" },
      quiz: {
        type: "array",
        minItems: 3,
        maxItems: 3,
        items: {
          type: "object",
          additionalProperties: false,
          properties: {
            question: { type: "string" },
            answer: { type: "string" },
          },
          required: ["question", "answer"],
        },
      },
    },
    required: ["title", "body", "points", "words", "why", "relation", "quiz"],
  };
}

